-- 1. Create Telemetry Buffer Tables (Short retention)
CREATE TABLE IF NOT EXISTS public.telemetry_sessions (
    session_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
    access_code_id UUID,
    device_type TEXT,
    operating_system TEXT,
    browser TEXT,
    browser_version TEXT,
    screen_size TEXT,
    orientation TEXT,
    timezone TEXT,
    app_version TEXT,
    login_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    logout_at TIMESTAMP WITH TIME ZONE,
    last_activity_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    session_duration_seconds INT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.telemetry_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID REFERENCES public.telemetry_sessions(session_id) ON DELETE CASCADE,
    user_id UUID,
    event_type TEXT NOT NULL,
    payload JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.telemetry_errors (
    error_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID REFERENCES public.telemetry_sessions(session_id) ON DELETE CASCADE,
    user_id UUID,
    error_type TEXT,
    error_message TEXT,
    app_version TEXT,
    context JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS for telemetry
ALTER TABLE public.telemetry_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telemetry_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telemetry_errors ENABLE ROW LEVEL SECURITY;

-- Allow inserts from authenticated users (or anon if we allow before login)
DROP POLICY IF EXISTS "Allow anon inserts to sessions" ON public.telemetry_sessions;
CREATE POLICY "Allow anon inserts to sessions" ON public.telemetry_sessions FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon updates to own sessions" ON public.telemetry_sessions;
CREATE POLICY "Allow anon updates to own sessions" ON public.telemetry_sessions FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow anon inserts to events" ON public.telemetry_events;
CREATE POLICY "Allow anon inserts to events" ON public.telemetry_events FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon inserts to errors" ON public.telemetry_errors;
CREATE POLICY "Allow anon inserts to errors" ON public.telemetry_errors FOR INSERT WITH CHECK (true);

